#include <iostream>

using namespace std;

int main() {
    double x1, y1, x2, y2, x3, y3;
    
    // Введення координат
    cout << "Введіть координати вершини A (x1 y1): ";
    cin >> x1 >> y1;
    cout << "Введіть координати вершини B (x2 y2): ";
    cin >> x2 >> y2;
    cout << "Введіть координати вершини C (x3 y3): ";
    cin >> x3 >> y3;
    
    // Перевірка на вироджений трикутник (точки на одній прямій)
    // Використовуємо косий добуток векторів
    double area_check = (x2 - x1) * (y3 - y1) - (y2 - y1) * (x3 - x1);
    if (area_check == 0) {
        cout << "Помилка: Точки лежать на одній прямій, трикутник не існує." << endl;
        return 1;
    }

    // Обчислення квадратів довжин сторін (за формулою квадрата відстані між точками)
    double ab2 = (x2 - x1) * (x2 - x1) + (y2 - y1) * (y2 - y1); // квадрат сторони AB
    double bc2 = (x3 - x2) * (x3 - x2) + (y3 - y2) * (y3 - y2); // квадрат сторони BC
    double ca2 = (x1 - x3) * (x1 - x3) + (y1 - y3) * (y1 - y3); // квадрат сторони CA
    
    // Перевірка умови гострокутного трикутника
    if ((ab2 + bc2 > ca2) && (bc2 + ca2 > ab2) && (ca2 + ab2 > bc2)) {
        cout << "Трикутник є гострокутним." << endl;
    } else {
        cout << "Трикутник НЕ є гострокутним (він прямокутний або тупокутний)." << endl;
    }
    
    return 0;
}
