#include <iostream>

using namespace std;

int main() {
    double a;
    
    // Запит на введення числа
    cout << "Введіть дійсне число a: ";
    cin >> a;

    // Перевірка належності до заданих інтервалів
    if ((a > 3 && a < 7) || (a >= 8 && a < 9) || (a > 11 && a < 22.4)) {
        cout << "Число належить заданому інтервалу." << endl;
    } else {
        cout << "Число НЕ належить заданому інтервалу." << endl;
    }

    return 0;
}
